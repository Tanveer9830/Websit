#!/usr/bin/env node
/**
 * Top Cloud one-command installer.
 *
 *   npm run topcloud
 *   npm run topcloud -- --skip-build
 *
 * Uses only Node built-ins until dependencies are installed, so it can bootstrap
 * a fresh clone. It never overwrites an existing .env, existing owner account,
 * existing settings or existing applications.
 */
import { spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const ENV_PATH = path.join(ROOT, ".env");
const DATA_DIR = path.join(ROOT, "data");
const DATABASE_PATH = path.join(DATA_DIR, "topcloud.db");
const args = new Set(process.argv.slice(2));
const skipBuild = args.has("--skip-build");

const C = {
  reset: "\x1b[0m",
  dim: "\x1b[2m",
  bold: "\x1b[1m",
  violet: "\x1b[38;5;141m",
  blue: "\x1b[38;5;75m",
  green: "\x1b[38;5;78m",
  yellow: "\x1b[38;5;220m",
  red: "\x1b[38;5;203m",
};

const line = (text = "") => console.log(text);
const ok = (text) => line(`  ${C.green}✓${C.reset} ${text}`);
const warn = (text) => line(`  ${C.yellow}!${C.reset} ${text}`);
const fail = (text) => line(`\n  ${C.red}✗ ${text}${C.reset}\n`);

function banner() {
  line();
  line(`${C.violet}${C.bold}  _____ ___  ____    ____ _     ___  _   _ ____`);
  line(`  |_   _/ _ \\|  _ \\  / ___| |   / _ \\| | | |  _ \\`);
  line(`    | || | | | |_) | | |   | |  | | | | | | | | | |`);
  line(`    | || |_| |  __/  | |___| |__| |_| | |_| | |_| |`);
  line(`    |_| \\___/|_|      \\____|_____|\\___/ \\___/|____/${C.reset}`);
  line();
  line(`${C.dim}  Secure staff application panel · one-command installer${C.reset}`);
  line();
}

function step(label) {
  line(`\n${C.violet}▸${C.reset} ${C.bold}${label}${C.reset}`);
}

function run(command, commandArgs, extraEnv = {}) {
  const result = spawnSync(command, commandArgs, {
    cwd: ROOT,
    stdio: "inherit",
    env: { ...process.env, ...extraEnv },
    shell: process.platform === "win32",
  });
  if (result.status !== 0) {
    throw new Error(`Command failed: ${command} ${commandArgs.join(" ")}`);
  }
}

function parseEnv(text) {
  const values = {};
  for (const lineText of text.split(/\r?\n/)) {
    const match = lineText.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[match[1]] = value;
  }
  return values;
}

function writeEnv() {
  const existing = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, "utf8") : "";
  const values = parseEnv(existing);
  const additions = [];
  const databaseUrl = `file:${DATABASE_PATH}`;

  if (!values.DATABASE_URL) additions.push(`DATABASE_URL="${databaseUrl}"`);
  if (!values.APP_URL) additions.push(`APP_URL="http://localhost:3000"`);
  const appUrl = values.APP_URL || "http://localhost:3000";
  const secure = appUrl.startsWith("https://");
  if (!values.COOKIE_SECURE) additions.push(`COOKIE_SECURE="${secure}"`);
  if (!values.SESSION_TTL_DAYS) additions.push(`SESSION_TTL_DAYS="7"`);
  if (!values.OWNER_USERNAME) additions.push(`OWNER_USERNAME="admin"`);
  if (!values.OWNER_EMAIL) additions.push(`OWNER_EMAIL="owner@topcloud.local"`);
  if (!values.SMTP_HOST) additions.push(`SMTP_HOST=""`);
  if (!values.SMTP_PORT) additions.push(`SMTP_PORT="587"`);
  if (!values.SMTP_SECURE) additions.push(`SMTP_SECURE="false"`);
  if (!values.SMTP_USER) additions.push(`SMTP_USER=""`);
  if (!values.SMTP_PASSWORD) additions.push(`SMTP_PASSWORD=""`);
  if (!values.EMAIL_FROM) additions.push(`EMAIL_FROM="Top Cloud <no-reply@topcloud.local>"`);

  if (additions.length > 0) {
    const header = existing
      ? "\n# ── Added by Top Cloud installer ──\n"
      : [
          "# Top Cloud environment — generated by the installer.",
          "# Never commit this file. It may contain SMTP credentials.",
          "# The SQLite/libSQL database lives in data/ and is git-ignored.",
          "",
        ].join("\n");
    writeFileSync(ENV_PATH, `${existing}${header}${additions.join("\n")}\n`, { mode: 0o600 });
    chmodSync(ENV_PATH, 0o600);
    ok(existing ? "completed missing .env values (existing values preserved)" : ".env created with secure file permissions (600)");
  } else {
    chmodSync(ENV_PATH, 0o600);
    ok(".env found — existing configuration preserved");
  }

  const finalEnv = parseEnv(readFileSync(ENV_PATH, "utf8"));
  for (const [key, value] of Object.entries(finalEnv)) {
    if (!process.env[key]) process.env[key] = value;
  }
  if (!process.env.DATABASE_URL) process.env.DATABASE_URL = databaseUrl;
  return finalEnv;
}

function countOwners(databaseUrl) {
  const script = `
    import { createClient } from "@libsql/client";
    const client = createClient({ url: process.env.DATABASE_URL });
    try {
      const result = await client.execute("SELECT count(*) AS count FROM users WHERE role = 'OWNER'");
      process.stdout.write(String(result.rows[0]?.count ?? 0));
    } catch (error) {
      process.stderr.write(String(error));
      process.exit(2);
    } finally {
      client.close();
    }
  `;
  const result = spawnSync(process.execPath, ["--input-type=module", "-e", script], {
    cwd: ROOT,
    encoding: "utf8",
    env: { ...process.env, DATABASE_URL: databaseUrl },
  });
  if (result.status !== 0) return null;
  const parsed = Number.parseInt(result.stdout.trim(), 10);
  return Number.isFinite(parsed) ? parsed : null;
}

function main() {
  banner();

  const major = Number.parseInt(process.versions.node.split(".")[0], 10);
  if (major < 20) {
    fail(`Node.js 20 or newer is required. You are running ${process.versions.node}.`);
    process.exit(1);
  }
  ok(`Node.js ${process.versions.node}`);

  step("1/6 · Prepare environment");
  mkdirSync(DATA_DIR, { recursive: true, mode: 0o700 });
  try {
    chmodSync(DATA_DIR, 0o700);
  } catch {
    /* best effort */
  }
  const env = writeEnv();
  ok(`database: ${env.DATABASE_URL || "(missing)"}`);
  ok(`public URL: ${env.APP_URL}`);

  step("2/6 · Install dependencies");
  run("npm", ["install", "--no-audit", "--no-fund"]);
  ok("dependencies installed");

  step("3/6 · Apply database migrations");
  run(process.execPath, ["scripts/migrate.mjs"], { DATABASE_URL: env.DATABASE_URL });
  ok("schema is up to date (existing data preserved)");

  step("4/6 · Initialise owner, settings and starter form");
  const ownersBefore = countOwners(env.DATABASE_URL);
  run("npx", ["tsx", "scripts/seed.ts"], { DATABASE_URL: env.DATABASE_URL });
  const ownersAfter = countOwners(env.DATABASE_URL);
  if (ownersAfter !== 1) {
    fail(
      `Security check failed: expected exactly one owner account, found ${ownersAfter ?? "unknown"}. ` +
        "Inspect the database before starting the server.",
    );
    process.exit(1);
  }

  step("5/6 · Build production bundle");
  if (skipBuild) {
    warn("Skipped (--skip-build). Run `npm run build` before `npm start`.");
  } else {
    run("npm", ["run", "build"]);
    ok("production build complete");
  }

  step("6/6 · Zero-trust post-install checks");
  if (existsSync(DATABASE_PATH)) {
    try {
      chmodSync(DATABASE_PATH, 0o600);
      ok("database file permissions set to 600");
    } catch {
      warn("could not set database file permissions");
    }
  }
  try {
    const envMode = statSync(ENV_PATH).mode & 0o777;
    if (envMode & 0o077) warn(`.env permissions are ${envMode.toString(8)} — expected 600`);
    else ok(".env permissions are 600");
  } catch {
    warn("could not verify .env permissions");
  }
  if (ownersAfter === 1 && ownersBefore === 0) ok("single owner created; no backdoor accounts exist");
  if (ownersAfter === 1 && ownersBefore === 1) ok("existing owner preserved (password was NOT reset)");

  line();
  line(`${C.violet}${C.bold}  ────────────────────────────────────────────────────────────${C.reset}`);
  line(`${C.bold}  Top Cloud is ready.${C.reset}`);
  line();
  if (ownersBefore === 0) {
    line(`  ${C.bold}First login${C.reset}   ${C.green}http://localhost:3000/admin/login${C.reset}`);
    line(`  ${C.bold}Username${C.reset}     admin`);
    line(`  ${C.bold}Password${C.reset}     admin`);
    line();
    line(`  ${C.yellow}${C.bold}SECURITY WARNING${C.reset}  Replace the temporary default password immediately.`);
    line(`  ${C.yellow}The panel locks the admin area until the password is changed.${C.reset}`);
  } else {
    line(`  ${C.bold}Existing owner credentials were not reset.${C.reset}`);
    line(`  Sign in at ${C.green}${env.APP_URL}/admin/login${C.reset} with your current password.`);
    line(`  Lost it? Use ${C.bold}npm run owner:recover${C.reset} on the server.`);
  }
  line();
  line(`  ${C.bold}Start${C.reset}         npm run start     ${C.dim}(production, port 3000)${C.reset}`);
  line(`  ${C.bold}Develop${C.reset}       npm run dev`);
  line(`  ${C.bold}Tests${C.reset}         npm test`);
  line(`  ${C.bold}Backup${C.reset}        npm run db:backup`);
  line();
  line(`  ${C.dim}Public site: ${env.APP_URL}   ·   Member portal: ${env.APP_URL}/dashboard${C.reset}`);
  line(`${C.violet}  ────────────────────────────────────────────────────────────${C.reset}`);
  line();
}

try {
  main();
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
